"""
Build the offline bundle assets of the app from data/core.json:
  frontend/assets/core/<photo>.jpg    – 640 px photos of the core monuments
  frontend/assets/cities/<city>.jpg   – city covers
  frontend/src/offline/coreMedia.ts   – static require() map (server path -> asset)

Usage:  python -m scripts.make_core_assets
"""

import json
from pathlib import Path

from PIL import Image, ImageOps

BASE = Path(__file__).parent.parent
FRONT = BASE.parent / "frontend"
STATIC = BASE / "static"


def main() -> None:
    core = json.loads((BASE / "data" / "core.json").read_text("utf-8"))["cities"]
    monuments = {
        m["id"]: m for m in json.loads((BASE / "data" / "monuments.json").read_text("utf-8"))
    }
    out_core = FRONT / "assets" / "core"
    out_cities = FRONT / "assets" / "cities"
    out_core.mkdir(parents=True, exist_ok=True)
    out_cities.mkdir(parents=True, exist_ok=True)

    entries: list[tuple[str, str]] = []
    for ids in core.values():
        for mid in ids:
            name = Path(monuments[mid]["image_url"]).name
            im = ImageOps.exif_transpose(Image.open(STATIC / "monuments" / name)).convert("RGB")
            im.thumbnail((640, 640), Image.LANCZOS)
            im.save(out_core / name, quality=72, optimize=True)
            entries.append((f"/static/monuments/{name}", f"core/{name}"))
    for city in core:
        src = STATIC / "cities" / f"{city}.jpg"
        im = Image.open(src).convert("RGB").resize((320, 320), Image.LANCZOS)
        im.save(out_cities / f"{city}.jpg", quality=75, optimize=True)
        entries.append((f"/static/cities/{city}.jpg", f"cities/{city}.jpg"))

    lines = [
        "// GENERATED by backend/scripts/make_core_assets.py - do not edit.",
        "/** Server media path -> bundled asset, so core photos and city covers work offline. */",
        "export const CORE_MEDIA: Record<string, number> = {",
    ]
    lines += [f"  '{path}': require('../../assets/{asset}')," for path, asset in entries]
    lines.append("};")
    (FRONT / "src" / "offline").mkdir(parents=True, exist_ok=True)
    (FRONT / "src" / "offline" / "coreMedia.ts").write_text("\n".join(lines) + "\n", "utf-8")
    total = sum(p.stat().st_size for p in out_core.glob("*.jpg"))
    total += sum(p.stat().st_size for p in out_cities.glob("*.jpg"))
    print(f"{len(entries)} assets, {total / 1024 / 1024:.1f} MB")


if __name__ == "__main__":
    main()
